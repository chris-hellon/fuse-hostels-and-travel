    private static readonly Dictionary<string, Country> ByCode = All.ToDictionary(c => c.Code, StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Nationalities are stored inconsistently: two-letter codes (Cloudbeds imports) or full names
    /// (typed in). Returns a display name either way.
    /// </summary>
    public static string DisplayName(string? value) =>
        string.IsNullOrWhiteSpace(value) ? ""
        : value.Length == 2 && ByCode.TryGetValue(value, out var country) ? country.Name
        : value;

    public static IEnumerable<string> Search(string? text) =>
        string.IsNullOrWhiteSpace(text)
            ? All.Select(c => c.Name)
            : All.Where(c => c.Name.Contains(text, StringComparison.OrdinalIgnoreCase)).Select(c => c.Name);
}

public static class Genders
{
    public static IReadOnlyList<string> Options { get; } = ["Male", "Female", "N/A"];

    /// <summary>Imports store M/F; show them the same way as values entered in the UI.</summary>
    public static string DisplayName(string? value) => value switch
    {
        null or "" => "",
        "M" => "Male",
        "F" => "Female",
        _ => value,
    };
}
